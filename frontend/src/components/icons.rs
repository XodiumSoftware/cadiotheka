//! Each icon is exposed as a component inside the [`Icon`] module, so callers can
//! write `<Icon::FullscreenEnter />`. The SVG paths are from the Phosphor icon set
//! The SVG paths are from the Phosphor icon set
//! (regular weight, 256×256 view box) and render at the size requested by the
//! caller via the `class` prop.

/// Declares an icon constant and a matching shorthand component.
///
/// `$name` is the `PascalCase` identifier used as the component name inside
/// [`Icon`]. `$const` is the corresponding `ICON_*` constant name that holds the
/// full SVG markup.
macro_rules! icon {
    ($name:ident, $const:ident, $svg:literal) => {
        pub const $const: &str = concat!(
            r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">"#,
            $svg,
            r#"</svg>"#
        );

        #[component]
        pub fn $name(#[prop(default = "w-4 h-4")] class: &'static str) -> impl IntoView {
            view! {
                <span class=format!("inline-flex items-center justify-center {class}") inner_html=$const />
            }
        }
    };
}

